/**
 * Dashboard UI text in the three admin languages. Shared by server code
 * (pages, Server Actions, upload routes) and client components, so it only
 * holds plain data and pure functions. The chosen language lives in the
 * ADMIN_LANG_COOKIE cookie (see lib/admin/lang.ts and AdminLang.tsx).
 */

export const ADMIN_LANGS = ["ku", "ar", "en"] as const;
export type AdminLang = (typeof ADMIN_LANGS)[number];
export const DEFAULT_ADMIN_LANG: AdminLang = "ar";
export const ADMIN_LANG_COOKIE = "idvet_admin_lang";

export function isAdminLang(value: unknown): value is AdminLang {
  return typeof value === "string" && (ADMIN_LANGS as readonly string[]).includes(value);
}

/** Each language's own name, for the switcher. */
export const ADMIN_LANG_NAMES: Record<AdminLang, string> = { ku: "کوردی", ar: "العربية", en: "English" };

export function adminDir(lang: AdminLang): "rtl" | "ltr" {
  return lang === "en" ? "ltr" : "rtl";
}

/** <html lang> value. */
export function adminHtmlLang(lang: AdminLang): string {
  return lang === "ku" ? "ckb" : lang;
}

/** Arabic count + noun, e.g. "3 صور", "صورة واحدة". */
function arCount(n: number, forms: { one: string; two: string; few: string; many: string }) {
  if (n === 1) return forms.one;
  if (n === 2) return forms.two;
  if (n === 0 || (n % 100 >= 3 && n % 100 <= 10)) return `${n} ${forms.few}`;
  return `${n} ${forms.many}`;
}

const enCount = (n: number, one: string, other: string) => `${n} ${n === 1 ? one : other}`;

